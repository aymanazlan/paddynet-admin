  const DICTS = { en, ms };
  const LOCALES = { en: "en-MY", ms: "ms-MY" };
  let lang = "en";
  try {
    const saved = localStorage.getItem("pn-lang");
    if (DICTS[saved]) lang = saved;
  } catch (e) { /* private mode */ }

  function t(key, vars) {
    let s = DICTS[lang][key] ?? en[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
    return s;
  }

  function applyStatic(root = document) {
    root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
    root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
    root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
    document.documentElement.lang = lang === "ms" ? "ms" : "en";
  }

  function setLang(value) {
    if (!DICTS[value]) return;
    lang = value;
    try { localStorage.setItem("pn-lang", value); } catch (e) { /* ignore */ }
    applyStatic();
  }

  window.I18N = {
    t,
    applyStatic,
    setLang,
    get lang() { return lang; },
    get locale() { return LOCALES[lang]; },
  };
